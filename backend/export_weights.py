"""One-off script: export the trained .npz weights to JSON for client-side inference.

Usage (from the repo root, after training):
    python backend/export_weights.py

Writes frontend/public/weights.json with every parameter array flattened to
row-major and rounded to 6 significant digits (floats are IEEE-754 doubles on
both sides, so 6 significant digits keeps downstream probabilities well
within 1e-4 of the NumPy reference).
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

WEIGHTS_PATH = Path(__file__).resolve().parent / "weights" / "mnist_weights.npz"
OUTPUT_PATH = Path(__file__).resolve().parent.parent / "frontend" / "public" / "weights.json"


def round_to_6_sig_figs(values: np.ndarray) -> list[float]:
    """Round every element to 6 significant digits for a compact JSON file."""
    return [float(f"{value:.6g}") for value in values.reshape(-1).tolist()]


def export() -> None:
    """Read the .npz archive and write the JSON weight manifest."""
    with np.load(WEIGHTS_PATH) as weights:
        manifest = {
            "format": "mnist-weights-v1",
            "description": "784 -> 128 -> 64 -> 10 network; arrays are row-major "
            "(in, out) so layer output = input x W + b. Generated by "
            "backend/export_weights.py from backend/weights/mnist_weights.npz.",
            "W1": {"shape": list(weights["W1"].shape), "data": round_to_6_sig_figs(weights["W1"])},
            "b1": {"shape": list(weights["b1"].shape), "data": round_to_6_sig_figs(weights["b1"])},
            "W2": {"shape": list(weights["W2"].shape), "data": round_to_6_sig_figs(weights["W2"])},
            "b2": {"shape": list(weights["b2"].shape), "data": round_to_6_sig_figs(weights["b2"])},
            "W3": {"shape": list(weights["W3"].shape), "data": round_to_6_sig_figs(weights["W3"])},
            "b3": {"shape": list(weights["b3"].shape), "data": round_to_6_sig_figs(weights["b3"])},
        }

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(json.dumps(manifest, separators=(",", ":")))
    size_mb = OUTPUT_PATH.stat().st_size / (1024 * 1024)
    print(f"Wrote {OUTPUT_PATH} ({size_mb:.2f} MB)")


if __name__ == "__main__":
    export()
